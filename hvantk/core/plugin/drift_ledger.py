"""The rebuild ledger: which committed drift baselines moved, and whether anything was
rebuilt since.

A fingerprint bump accepts a new upstream baseline, which is also the signal that an
artifact built before it may now be stale. ``hvantk/resources/drift_ledger.json``
records that fact as one row per dataset, in the same commit as the fingerprint it
describes; without it the fact survives only in git history.

This module is the one implementation of that row, used by both writers:

* the drift bot (``.github/scripts/drift_to_pr.py``), which records its rows only once
  its stability check and its anti-churn guards have passed, right before it commits;
* ``hvantk drift --regenerate``, for a baseline regenerated by hand. Before #408 that
  path wrote no row at all, so a bump accepted by hand (#370, #378, #381) shipped
  without one.

The bot regenerates with ``--no-ledger-row`` and keeps recording at its own point, so a
dataset it skips or drops mid-batch never leaves a row behind.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Mapping

# The comparator the drift check itself uses, so "materially changed" here means
# exactly what "drifted" means there: equal once fetched_at / probe_version /
# informational are dropped, with the same {added, removed, changed} diff shape the
# drift report carries.
from .drift_runner import _compare_fingerprints

# hvantk/core/plugin/drift_ledger.py -> parents[2] is hvantk/.
LEDGER_PATH = Path(__file__).resolve().parents[2] / "resources" / "drift_ledger.json"

#: ``accepted_in`` for a row recorded by ``hvantk drift --regenerate`` when the caller
#: names no PR or branch with ``--accepted-in``. The bot always names its branch.
MANUAL_ACCEPTED_IN = "manual"

# Fingerprint keys that carry the SCHEMA signal. `headers` is the column list;
# `checksums` is a hash of the column-header row for the header-hashing probes
# (clingen, gencc, hgnc) or of the VCF meta-header (clinvar), so a moved checksum means
# the columns moved. A probe that puts HTTP metadata here instead makes this tier
# constant -- see #333, and `extras` for where a pure content signal belongs.
SCHEMA_KEYS = frozenset({"headers", "checksums"})


def classify_risk(diff: Mapping[str, Any] | None) -> str:
    """Classify a drift diff as ``"routine"`` or ``"schema"``.

    Routine means the schema signal is unchanged and only content/version moved --
    safe to batch with other routine datasets into one PR. Schema means the column
    list or header hash moved, or the fingerprint gained/lost a top-level key, and
    the plugin's builder.py may need a change.

    Defaults to ``"schema"`` for anything it cannot read. Misclassifying a schema
    change as routine would bury it in a batch; the reverse just opens one extra PR.
    """
    if not isinstance(diff, dict) or not diff:
        return "schema"
    if diff.get("added") or diff.get("removed"):
        return "schema"
    changed = diff.get("changed") or {}
    if not isinstance(changed, dict):
        return "schema"
    if SCHEMA_KEYS & set(changed):
        return "schema"
    return "routine"


def ledger_entry(*, diff: Mapping[str, Any] | None, accepted_in: str, now: str) -> dict:
    """One ledger row. ``rebuilt_at`` starts None and is set by whoever rebuilds
    (``hvantk drift --mark-rebuilt``); a value older than ``last_upstream_change`` is
    the stale-artifact condition ``hvantk drift --ledger`` reports.
    """
    return {
        "last_upstream_change": now,
        "accepted_in": accepted_in,
        "signal": classify_risk(diff),
        "rebuilt_at": None,
    }


def ledger_update(
    ledger: Mapping[str, Any],
    *,
    dataset: str,
    diff: Mapping[str, Any] | None,
    accepted_in: str,
    now: str,
) -> dict:
    """Return a copy of ``ledger`` with ``dataset``'s row replaced. Never touches other
    rows, and never mutates its input."""
    out = dict(ledger)
    out[dataset] = ledger_entry(diff=diff, accepted_in=accepted_in, now=now)
    return out


def load_ledger(path: Path) -> dict:
    """Read the ledger. A missing or corrupt file -- or JSON that parses but is not an
    object -- yields {} rather than raising: a broken ledger must not block a drift PR
    or a regenerate, it just starts recording afresh.

    `json.loads(text) or {}` looks like it covers "empty/invalid", but `or` only
    substitutes on a FALSY parse (`[]`, `0`, `""`, `null`); a populated list or a
    non-empty string is truthy and would pass straight through to callers that all
    assume a dict.
    """
    path = Path(path)
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text())
    except ValueError:
        return {}
    return data if isinstance(data, dict) else {}


def write_ledger(ledger: Mapping[str, Any], path: Path) -> None:
    """Write the whole ledger back, in the byte format every writer has always used
    (indent 2, sorted keys, trailing newline), so rows never churn on re-serialisation.
    """
    Path(path).write_text(json.dumps(ledger, indent=2, sort_keys=True) + "\n")


def record_changes(
    changes: Iterable[tuple[str, Mapping[str, Any] | None]],
    *,
    accepted_in: str,
    path: Path,
    now: str | None = None,
) -> dict:
    """Record one row per ``(dataset, diff)`` pair, all stamped with the same ``now``,
    and write the ledger back. Rows for every other dataset are copied through
    untouched. Returns the ledger as written.

    ``path`` is required rather than defaulting to `LEDGER_PATH`: the bot resolves the
    ledger inside the checkout it commits from, and tests point every writer at a
    temporary file, so no caller should reach the tracked ledger by omission.
    """
    now = now or datetime.now(timezone.utc).isoformat()
    ledger = load_ledger(path)
    for dataset, diff in changes:
        ledger = ledger_update(
            ledger, dataset=dataset, diff=diff, accepted_in=accepted_in, now=now
        )
    write_ledger(ledger, path)
    return ledger


def read_baseline(path: Path) -> dict | None:
    """The committed baseline at ``path``, read before a regenerate overwrites it.

    None means there was no baseline file at all: a dataset's first capture, which is
    not an upstream change, so `record_regeneration` records no row for it. A file that
    exists but cannot be read as a JSON object reads as {}: nothing shows the new
    capture equals it, so the change is recorded, and every key then reads as added,
    which `classify_risk` tiers as schema.
    """
    try:
        text = Path(path).read_text()
    except FileNotFoundError:
        return None
    except OSError:
        return {}
    try:
        data = json.loads(text)
    except ValueError:
        return {}
    return data if isinstance(data, dict) else {}


def record_regeneration(
    dataset: str,
    *,
    previous: Mapping[str, Any] | None,
    regenerated: Mapping[str, Any],
    accepted_in: str,
    path: Path,
    now: str | None = None,
) -> dict | None:
    """Record ``dataset``'s row if a regenerate materially changed its baseline.

    ``previous`` is what `read_baseline` returned before the regenerate; ``regenerated``
    is the fingerprint it wrote. They are diffed exactly as a drift check diffs a
    baseline against a live probe, so the row's ``signal`` is the tier the bot would
    have given the same change. Returns the recorded row, or None when no row was
    written: no earlier baseline, or nothing changed beyond the ignored keys (a re-run,
    or a ``probe_version`` bump whose output is otherwise identical).
    """
    if previous is None:
        return None
    diff = _compare_fingerprints(dict(previous), dict(regenerated))
    if diff is None:
        return None
    ledger = record_changes(
        [(dataset, diff)], accepted_in=accepted_in, path=path, now=now
    )
    return ledger[dataset]
