"""Tests for ancestry filter module.

These tests require Hail and use synthetic MatrixTables generated by
the Balding-Nichols population genetics model.
"""

import pytest

from hvantk.ancestry.filter import (
    filter_to_autosomes,
    filter_to_biallelic_snps,
    compute_variant_qc,
    filter_variants_for_ancestry,
    ld_prune_variants,
    prepare_ancestry_variants,
)


@pytest.mark.hail
class TestFilterToAutosomes:
    """Tests for filter_to_autosomes function."""

    def test_autosomes_only(self, hail_session, small_merged_mt):
        """Filter should keep only autosomal variants."""
        mt_filtered = filter_to_autosomes(small_merged_mt)

        # All remaining variants should be on autosomes
        # Balding-Nichols generates on chromosome 1 by default
        n_filtered = mt_filtered.count_rows()
        assert n_filtered > 0

        # Verify all loci are autosomal
        non_autosomal = mt_filtered.filter_rows(
            ~mt_filtered.locus.in_autosome()
        ).count_rows()
        assert non_autosomal == 0


@pytest.mark.hail
class TestFilterToBiallelicSnps:
    """Tests for filter_to_biallelic_snps function."""

    def test_biallelic_snps_only(self, hail_session, small_merged_mt):
        """Filter should keep only biallelic SNPs."""
        import hail as hl

        mt_filtered = filter_to_biallelic_snps(small_merged_mt)

        # Check all variants are biallelic
        n_multiallelic = mt_filtered.filter_rows(
            hl.len(mt_filtered.alleles) != 2
        ).count_rows()
        assert n_multiallelic == 0

        # Check all variants are SNPs
        n_non_snp = mt_filtered.filter_rows(
            ~hl.is_snp(mt_filtered.alleles[0], mt_filtered.alleles[1])
        ).count_rows()
        assert n_non_snp == 0


