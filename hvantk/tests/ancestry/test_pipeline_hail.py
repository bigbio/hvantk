@pytest.mark.hail
class TestPipelineEdgeCases:
    """Tests for pipeline edge cases."""

    def test_min_prob_zero_assigns_all(
        self, hail_session, synthetic_query_mt, synthetic_reference_mt
    ):
        """min_prob=0 should assign all samples."""
        result = run_ancestry_inference(
            query_mt=synthetic_query_mt,
            reference_mt=synthetic_reference_mt,
            ancestry_col="ancestry",
            config=PipelineConfig(
                skip_ld_pruning=True,
                min_shared_variants=100,
                validate_model=False,
                min_prob=0.0,  # Accept all predictions
            ),
        )

        # No samples should be unassigned
        query_preds = result.get_query_predictions()
        n_unassigned = (query_preds[PREDICTED_ANCESTRY_COL] == "unassigned").sum()
        assert n_unassigned == 0

    def test_high_min_prob_increases_unassigned(
        self, hail_session, synthetic_query_mt, synthetic_reference_mt
    ):
        """Higher min_prob should increase unassigned count."""
        # Low threshold
        result_low = run_ancestry_inference(
            query_mt=synthetic_query_mt,
            reference_mt=synthetic_reference_mt,
            ancestry_col="ancestry",
            config=PipelineConfig(
                skip_ld_pruning=True,
                min_shared_variants=100,
                validate_model=False,
                min_prob=0.5,
            ),
        )

        # High threshold
        result_high = run_ancestry_inference(
            query_mt=synthetic_query_mt,
            reference_mt=synthetic_reference_mt,
            ancestry_col="ancestry",
            config=PipelineConfig(
                skip_ld_pruning=True,
                min_shared_variants=100,
                validate_model=False,
                min_prob=0.99,
            ),
        )

        # Higher threshold should have more unassigned
        low_unassigned = result_low.pipeline_stats["n_query_unassigned"]
        high_unassigned = result_high.pipeline_stats["n_query_unassigned"]
        assert high_unassigned >= low_unassigned
